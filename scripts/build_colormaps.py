"""Regenerate src/nctui/_cmapdata.py from matplotlib's colour maps.

nctui ships the lookup tables as plain data so that starting the TUI doesn't
need to import matplotlib.

    pixi run python scripts/build_colormaps.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib
import numpy as np

SEQUENTIAL = ["viridis", "plasma", "inferno", "magma", "cividis", "turbo",
              "Greys_r", "Blues", "YlGnBu", "YlOrRd"]
DIVERGING = ["RdBu_r", "coolwarm", "BrBG", "PiYG", "seismic"]
CYCLIC = ["twilight"]

OUT = Path(__file__).resolve().parent.parent / "src" / "nctui" / "_cmapdata.py"


def table(name: str) -> str:
    cmap = matplotlib.colormaps[name].resampled(256)
    rgb = (np.asarray(cmap(np.linspace(0, 1, 256)))[:, :3] * 255).round().astype(np.uint8)
    return rgb.tobytes().hex()


def main() -> None:
    lines = [
        '"""Colour-map lookup tables (256 RGB entries each), generated by',
        'scripts/build_colormaps.py from matplotlib. Do not edit by hand."""',
        "",
        f"SEQUENTIAL = {SEQUENTIAL!r}",
        f"DIVERGING = {DIVERGING!r}",
        f"CYCLIC = {CYCLIC!r}",
        "",
        "TABLES = {",
    ]
    for name in SEQUENTIAL + DIVERGING + CYCLIC:
        hexstr = table(name)
        lines.append(f"    {name!r}: (")
        for i in range(0, len(hexstr), 96):
            lines.append(f"        {hexstr[i:i + 96]!r}")
        lines.append("    ),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
